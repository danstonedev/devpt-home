import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, extname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const simlab = resolve(process.env.DEVPT_SIMLAB_SOURCE || resolve(root, '../simlab'));
const catalogPath = resolve(simlab, 'apps/mission-shell/src/lib/teaching/catalog.json');
const catalog = JSON.parse(readFileSync(catalogPath, 'utf8'));
if (catalog.status !== 'local-development-only' || !catalog.activities?.length) throw new Error('Expected the canonical local review catalog.');
const mediaSources = {
  logo: resolve(root, 'assets/devpt-logo.png'),
  simlab: resolve(root, 'assets/simlab-logo.png'),
  simemr: resolve(root, 'assets/brand/simemr-wordmark.png'),
  painmap: resolve(root, 'assets/brand/3dpain-wordmark.png'),
  vestibular: resolve(simlab, 'apps/mission-shell/src/lib/lab/vestibular/assets/vestibular-demo-preview.png'),
  rom: resolve(root, 'assets/shots/movement-lab.jpg'),
  examination: resolve(root, 'assets/features/simlab/passive-rom.png'),
  bppv: resolve(simlab, '.cache/public-workspace-results/public-workspace-native-pu-0d8fd-ervation-without-remounting/native-public-bppv.png'),
  emr: resolve(root, 'assets/features/emrs/workspace.png'),
  anatomy: resolve(root, 'assets/teaching/hip-anatomy.png'),
  biomechanics: resolve(root, 'assets/teaching/hip-biomechanics.png'),
  manual: resolve(root, 'assets/teaching/hip-manual-therapy.png'),
  gait: resolve(root, 'assets/teaching/gait.png'),
  vitals: resolve(root, 'assets/teaching/live-vitals.png'),
  neuro: resolve(root, 'assets/teaching/neural-pathways.png'),
  imaging: resolve(root, 'assets/teaching/synthetic-imaging.png'),
};
const media = Object.fromEntries(Object.entries(mediaSources).filter(([,path]) => existsSync(path)).map(([key,path]) => {
  const type = extname(path) === '.jpg' ? 'image/jpeg' : 'image/png';
  return [key, `data:${type};base64,${readFileSync(path).toString('base64')}`];
}));
// Generated metadata/posters, never a second maintained resource or model library.
writeFileSync(resolve(root, 'local-site-config.js'), `/* Generated by scripts/build-local-site.mjs from canonical sources. Local review only. */\nconst MEDIA=${JSON.stringify(media)};\nconst NATIVE_CATALOG=${JSON.stringify(catalog)};\nconst NATIVE_SOURCE_BASE='/native';\nconst EMR_SOURCE_BASE='/emr-native';\n`);
const fonts = [400,600,700,800].map(weight => {
  const path = resolve(simlab, `apps/mission-shell/node_modules/@fontsource/hanken-grotesk/files/hanken-grotesk-latin-${weight}-normal.woff2`);
  return `@font-face{font-family:Hanken;src:url(data:font/woff2;base64,${readFileSync(path).toString('base64')}) format('woff2');font-weight:${weight};font-display:swap}`;
}).join('\n');
writeFileSync(resolve(root, 'local-site-fonts.css'), fonts + '\n');
console.log(`Built local site configuration from ${catalogPath} (${catalog.activities.length} resources).`);
