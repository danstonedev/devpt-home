#!/usr/bin/env node
/**
 * Extract only the public foundation's canonical variables from the active EMR
 * app.css @theme block. Presentation CSS remains deliberately small and local.
 *
 * Sync:  node scripts/sync-emr-foundation.mjs --source ../devpt-emr-platform
 * Drift: node scripts/sync-emr-foundation.mjs --check --source ../devpt-emr-platform
 * A source-free checkout can explicitly verify its committed snapshot with
 * --check --snapshot-only; that does not claim to check the upstream repository.
 */
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const siteRoot = fileURLToPath(new URL("../", import.meta.url));
const cssPath = path.join(siteRoot, "emr-foundation.css");
const manifestPath = path.join(
  siteRoot,
  "assets/brand/emr-foundation.source.json",
);
const begin =
  "/* BEGIN EMR TOKENS — generated by scripts/sync-emr-foundation.mjs */";
const end = "/* END EMR TOKENS */";
const selectedTokens = [
  "--color-brand-gray",
  "--color-brand-green",
  "--color-brand-green-dark",
  "--color-brand-green-light",
  "--color-brand-orange",
  "--color-brand-green-onwhite",
  "--color-accent",
  "--color-accent-strong",
  "--color-text",
  "--color-text-muted",
  "--color-text-subtle",
  "--color-neutral-50",
  "--color-neutral-100",
  "--color-neutral-200",
  "--color-neutral-300",
  "--color-neutral-400",
  "--color-neutral-500",
  "--color-neutral-600",
  "--color-neutral-700",
  "--color-neutral-800",
  "--color-neutral-900",
  "--color-editor-bg",
  "--color-surface",
  "--color-surface-subtle",
  "--color-surface-inset",
  "--color-input-bg",
  "--color-input-border",
  "--color-control-hover-border",
  "--color-topbar-start",
  "--color-topbar-end",
  "--color-section-header-start",
  "--color-section-header-end",
  "--color-section-header-hover-start",
  "--color-section-header-hover-end",
  "--color-section-divider",
  "--color-subsection-header-start",
  "--color-subsection-header-end",
  "--color-btn-add-bg",
  "--color-btn-add-bg-hover",
  "--font-family-sans",
  "--font-mono",
  "--focus-ring",
  "--space-1",
  "--space-2",
  "--space-3",
  "--space-4",
  "--space-5",
  "--space-6",
  "--space-8",
  "--radius-sm",
  "--radius-button",
  "--radius-card",
  "--radius-pill",
  "--app-header-h",
];
const provenanceFiles = [
  "src/app.css",
  "src/routes/+layout.svelte",
  "src/lib/styles/emrHeaders.css",
  "src/lib/styles/noteGuide.css",
];

function digest(value) {
  return createHash("sha256").update(value).digest("hex");
}

function normalize(value) {
  // Compare CSS values, allowing a formatter to wrap functions or change the
  // font-family quote style without falsely reporting a design token change.
  return value
    .replace(/(["'])([^"']*)\1/g, (_, _quote, content) =>
      JSON.stringify(content),
    )
    .replace(/\s+/g, " ")
    .replace(/\(\s+/g, "(")
    .replace(/\s+\)/g, ")")
    .trim();
}

function readDeclarations(css) {
  const declarations = new Map();
  const clean = css.replace(/\/\*[\s\S]*?\*\//g, "");
  for (const [, name, value] of clean.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) {
    if (declarations.has(name)) {
      throw new Error(`Duplicate foundation token: ${name}`);
    }
    declarations.set(name, normalize(value));
  }
  return declarations;
}

function themeTokens(appCss) {
  const start = appCss.indexOf("@theme {");
  if (start < 0) throw new Error("No active @theme block in EMR src/app.css");
  const close = appCss.indexOf("\n}", start);
  if (close < 0) throw new Error("Unclosed EMR @theme block");
  const declarations = readDeclarations(appCss.slice(start, close));
  return Object.fromEntries(
    selectedTokens.map((name) => {
      if (!declarations.has(name)) {
        throw new Error(`Active EMR @theme no longer declares ${name}`);
      }
      return [name, declarations.get(name)];
    }),
  );
}

function tokenBlock(tokens) {
  return `${begin}\n:root {\n${selectedTokens
    .map((name) => `  ${name}: ${tokens[name]};`)
    .join("\n")}\n}\n${end}`;
}

function replaceTokenBlock(css, replacement) {
  const start = css.indexOf(begin);
  const stop = css.indexOf(end, start);
  if (start < 0 || stop < 0) {
    throw new Error("Missing generated token markers in emr-foundation.css");
  }
  if (css.indexOf(begin, start + begin.length) >= 0) {
    throw new Error("Duplicate generated foundation token block");
  }
  return css.slice(0, start) + replacement + css.slice(stop + end.length);
}

function compareTokens(expected, actual, label) {
  const errors = selectedTokens
    .filter((name) => expected[name] !== actual[name])
    .map(
      (name) =>
        `  ${name}: expected ${expected[name]}, found ${actual[name] ?? "missing"}`,
    );
  if (errors.length) {
    throw new Error(`${label} has drifted:\n${errors.join("\n")}`);
  }
}

function verifySnapshot(manifest, css) {
  if (manifest.schemaVersion !== 1) {
    throw new Error("Unsupported EMR foundation manifest version");
  }
  if (
    JSON.stringify(Object.keys(manifest.tokens ?? {})) !==
    JSON.stringify(selectedTokens)
  ) {
    throw new Error(
      "Foundation manifest token selection differs from the sync script",
    );
  }
  if (manifest.tokenSha256 !== digest(JSON.stringify(manifest.tokens))) {
    throw new Error("Foundation manifest token hash is invalid");
  }
  const start = css.indexOf(begin);
  const stop = css.indexOf(end, start);
  replaceTokenBlock(css, ""); // Validate marker boundaries even in read-only mode.
  const cssTokens = Object.fromEntries(
    readDeclarations(css.slice(start + begin.length, stop)),
  );
  compareTokens(manifest.tokens, cssTokens, "Generated CSS token block");
  const rest = css.slice(0, start) + css.slice(stop + end.length);
  const overrides = readDeclarations(rest);
  const duplicate = selectedTokens.find((name) => overrides.has(name));
  if (duplicate)
    throw new Error(
      `Canonical token overridden outside generated block: ${duplicate}`,
    );
}

async function main() {
  const args = process.argv.slice(2);
  const options = { check: false, snapshotOnly: false, source: null };
  for (let i = 0; i < args.length; i += 1) {
    const arg = args[i];
    if (arg === "--check") options.check = true;
    else if (arg === "--snapshot-only") options.snapshotOnly = true;
    else if (
      arg === "--source" &&
      args[i + 1] &&
      !args[i + 1].startsWith("--")
    ) {
      options.source = path.resolve(args[++i]);
    } else if (arg === "--help") {
      process.stdout.write(
        "Usage: node scripts/sync-emr-foundation.mjs [--check] [--source EMR_PATH]\n" +
          "       node scripts/sync-emr-foundation.mjs --check --snapshot-only\n" +
          "Without --source, the sibling ../devpt-emr-platform checkout is used.\n" +
          "Upstream source is required unless --check --snapshot-only is explicit.\n",
      );
      return;
    } else throw new Error(`Unknown or incomplete argument: ${arg}`);
  }
  if (options.snapshotOnly && (!options.check || options.source)) {
    throw new Error(
      "Use --snapshot-only only with --check and without --source",
    );
  }
  const css = await readFile(cssPath, "utf8");
  if (options.snapshotOnly) {
    const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
    verifySnapshot(manifest, css);
    process.stdout.write(
      `Verified ${selectedTokens.length} committed EMR foundation tokens. Upstream source was not checked (--snapshot-only).\n`,
    );
    return;
  }

  const sourceRoot =
    options.source ?? path.resolve(siteRoot, "../devpt-emr-platform");
  let sourceFiles;
  try {
    sourceFiles = await Promise.all(
      provenanceFiles.map((file) =>
        readFile(path.join(sourceRoot, file), "utf8"),
      ),
    );
  } catch (error) {
    throw new Error(
      `Cannot read active EMR source at ${sourceRoot}. Supply --source EMR_PATH. ` +
        "For a source-free snapshot check, explicitly use --check --snapshot-only.",
      { cause: error },
    );
  }
  const tokens = themeTokens(sourceFiles[0]);
  if (options.check) {
    const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
    verifySnapshot(manifest, css);
    compareTokens(tokens, manifest.tokens, "Committed EMR foundation snapshot");
    process.stdout.write(
      `Verified ${selectedTokens.length} foundation tokens against active EMR src/app.css at ${sourceRoot}.\n`,
    );
    return;
  }

  let revision = null;
  try {
    revision = execFileSync("git", ["-C", sourceRoot, "rev-parse", "HEAD"], {
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim();
  } catch {
    // A source archive can still supply the canonical CSS; hashes identify it.
  }
  const manifest = {
    schemaVersion: 1,
    source: {
      repository: "https://github.com/danstonedev/devpt-emr-platform",
      revision,
      tokenLocation: "src/app.css @theme",
      files: Object.fromEntries(
        provenanceFiles.map((file, index) => [
          file,
          digest(sourceFiles[index]),
        ]),
      ),
    },
    tokenSha256: digest(JSON.stringify(tokens)),
    tokens,
  };
  await mkdir(path.dirname(manifestPath), { recursive: true });
  await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
  await writeFile(cssPath, replaceTokenBlock(css, tokenBlock(tokens)));
  process.stdout.write(
    `Synced ${selectedTokens.length} public foundation tokens from active EMR src/app.css.\n`,
  );
}

main().catch((error) => {
  process.stderr.write(`${error.message}\n`);
  process.exitCode = 1;
});
